  await ir(p, '/backoffice/analise-documentos'); await escolher(p, 'Mineradora Exemplo'); await foto(p, M, '02-analise-documentos', { full: true })
  await clicar(p, '✏️ Editar', 3000); await foto(p, M, '03-editar-documento', { full: true })
  await ir(p, '/backoffice/processos'); await escolher(p, 'Mineradora Exemplo'); await clicar(p, 'Pesquisar', 5000); await foto(p, M, '04-processos', { full: true })
  await ir(p, `/backoffice/analise/${BETA}`, 5000); await foto(p, M, '05-ficha-processo', { full: true })
  await ir(p, `/backoffice/analise/${CONSTRUTORA}`, 5000); await escolher(p, 'ELOS'); await foto(p, M, '06-ficha-coleta-automatica', { full: true })
  await ir(p, '/backoffice/homologados'); await borrar(p, 'Ver Ficha'); await foto(p, M, '07-homologados')
  await ir(p, '/backoffice/convites'); await escolher(p, 'Mineradora Exemplo'); await clicar(p, 'Pesquisar', 4000); await foto(p, M, '08-convites')
