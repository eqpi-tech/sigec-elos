// Imagens do Manual do Comprador — node scripts/manuais/shoot_comprador.cjs
// Fotografa como Free e depois como Pro (alterna o plano da compradora fictícia no staging)
const { execSync } = require('child_process'), path = require('path'), fs = require('fs')
const { browser, entrar, ir, foto, borrar, clicar } = require('./shoot_lib.cjs')
const M = 'comprador', CONSTRUTORA = 'e1a00000-0000-4000-8000-000000000101'
const env = fs.readFileSync(path.resolve(__dirname, '../../.env'), 'utf8')
const S = (env.match(/^SUPABASE_DB_URL_PREVIEW=(.*)$/m) || [])[1].replace(/"/g, '')
const plano = (pl) => execSync(`PGGSSENCMODE=disable /usr/local/opt/libpq/bin/psql "${S}" -X -q -c "update user_roles set buyer_plan='${pl}', buyer_plan_expires_at=${pl === 'pro' ? "now()+interval '1 year'" : 'null'} where user_id='e1a00000-0000-4000-8000-0000000000c1' and role='BUYER'"`)
;(async () => {
  const b = await browser()
  plano('free')
  let p = await entrar(b, 'beatriz.rocha@comercialexemplo.com.br')
  await ir(p, '/comprador'); await foto(p, M, '01-marketplace-inicio')
  await clicar(p, '🔍 Buscar Fornecedores', 6000); await borrar(p, 'Ver Perfil'); await foto(p, M, '02-marketplace-resultados')
  await ir(p, `/comprador/fornecedor/${CONSTRUTORA}`); await foto(p, M, '03-ficha-free', { full: true })
  await ir(p, '/comprador/plano'); await foto(p, M, '04-plano-free')
  await ir(p, '/comprador/convites'); await foto(p, M, '05-convites')
  await p.context().close()
  plano('pro')
  p = await entrar(b, 'beatriz.rocha@comercialexemplo.com.br')
  await ir(p, `/comprador/fornecedor/${CONSTRUTORA}`); await clicar(p, '👥 Sócios'); await foto(p, M, '06-ficha-pro-contatos')
  await ir(p, '/comprador/cotacoes'); await clicar(p, 'Manutenção preventiva'); await foto(p, M, '07-cotacoes', { full: true })
  await ir(p, '/comprador'); await clicar(p, '🔍 Buscar Fornecedores', 6000); await borrar(p, 'Ver Perfil'); await foto(p, M, '08-marketplace-pro')
  await b.close()
})()
